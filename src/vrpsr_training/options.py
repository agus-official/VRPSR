import argparse

def parse_sr_args(input_args=None):
    parser = argparse.ArgumentParser(description='VRPSR sr training')
    parser.add_argument('--gan_loss_type', default='multilevel_sigmoid_s')
    parser.add_argument('--lambda_gan', default=0.5, type=float)
    parser.add_argument('--lambda_l2', default=2.0, type=float)
    parser.add_argument('--lambda_lpips', default=5.0, type=float)
    parser.add_argument('--base_config', type=str, default='configs/vrpsr_degradation.yaml')
    parser.add_argument('--fixed_qp', type=int, default=None)
    parser.add_argument('--fixed_codec_type', type=str, default=None)
    parser.add_argument('--fixed_qp_val', type=int, default=38)
    parser.add_argument('--fixed_codec_type_val', type=str, default='libx264')
    parser.add_argument('--eval_freq', type=int, default=1000)
    parser.add_argument('--num_samples_eval', type=int, default=100, help='Number of samples to use for all evaluation')
    parser.add_argument('--sd_path')
    parser.add_argument('--pretrained_sr_path', type=str, default=None, required=True)
    parser.add_argument('--pretrained_sim_path', type=str, default=None, required=True)
    parser.add_argument('--de_net_path', required=True)
    parser.add_argument('--lora_rank_unet', default=32, type=int)
    parser.add_argument('--lora_rank_vae', default=16, type=int)
    parser.add_argument('--output_dir', required=True)
    parser.add_argument('--seed', type=int, default=None, help='A seed for reproducible training.')
    parser.add_argument('--train_batch_size', type=int, help='Batch size (per device) for the training dataloader.', default=2)
    parser.add_argument('--max_train_steps', type=int, default=50000)
    parser.add_argument('--checkpointing_steps', type=int, default=1000)
    parser.add_argument('--gradient_accumulation_steps', type=int, help='Number of updates steps to accumulate before performing a backward/update pass.', default=4)
    parser.add_argument('--gradient_checkpointing', action='store_true')
    parser.add_argument('--learning_rate', type=float, default=2e-05)
    parser.add_argument('--lr_scheduler', type=str, default='constant', help='The scheduler type to use. Choose between ["linear", "cosine", "cosine_with_restarts", "polynomial", "constant", "piecewise_constant", "constant_with_warmup"]')
    parser.add_argument('--lr_warmup_steps', type=int, default=500, help='Number of steps for the warmup in the lr scheduler.')
    parser.add_argument('--lr_num_cycles', type=int, default=1, help='Number of hard resets of the lr in cosine_with_restarts scheduler.')
    parser.add_argument('--lr_power', type=float, default=0.1, help='Power factor of the polynomial scheduler.')
    parser.add_argument('--dataloader_num_workers', type=int, default=8)
    parser.add_argument('--adam_beta1', type=float, default=0.9, help='The beta1 parameter for the Adam optimizer.')
    parser.add_argument('--adam_beta2', type=float, default=0.999, help='The beta2 parameter for the Adam optimizer.')
    parser.add_argument('--adam_weight_decay', type=float, default=0.01, help='Weight decay to use.')
    parser.add_argument('--adam_epsilon', type=float, default=1e-08, help='Epsilon value for the Adam optimizer')
    parser.add_argument('--max_grad_norm', default=1.0, type=float, help='Max gradient norm.')
    parser.add_argument('--allow_tf32', action='store_true', help='Whether or not to allow TF32 on Ampere GPUs. Can be used to speed up training. For more information, see https://pytorch.org/docs/stable/notes/cuda.html#tensorfloat-32-tf32-on-ampere-devices')
    parser.add_argument('--mixed_precision', type=str, choices=['no', 'fp16', 'bf16'], default='no')
    parser.add_argument('--enable_xformers_memory_efficient_attention', action='store_true', help='Whether or not to use xformers.')
    parser.add_argument('--set_grads_to_none', action='store_true')
    parser.add_argument('--train_data', required=True, help='Image directory or text file containing image paths')
    parser.add_argument('--val_data', required=True, help='Validation image directory or path list')
    parser.add_argument('--wandb', action='store_true', help='Enable offline WandB logging on rank zero')
    args = parser.parse_args(input_args)
    for name in ('train_batch_size', 'gradient_accumulation_steps', 'checkpointing_steps', 'max_train_steps', 'num_training_epochs', 'num_samples_eval'):
        if hasattr(args, name) and getattr(args, name) <= 0:
            parser.error(name + ' must be positive')
    if args.eval_freq < 0:
        parser.error('eval_freq must be nonnegative (0 disables evaluation)')
    if hasattr(args, 'stop_steps') and args.stop_steps is not None and (args.stop_steps <= 0):
        parser.error('stop_steps must be positive')
    return args

